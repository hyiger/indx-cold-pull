"""INDX cold pull: G-code generator, serial step table and the guarded serial session.

Ported from ../index.html (hyiger/indx-cold-pull), which mirrors generate_cold_pull_gcode() and the
guarded serial path of the hyiger/PrusaSlicer fork (src/slic3r/Utils/MaintenanceSerial.cpp).
generate_gcode() and build_steps() must stay byte-identical to generateGcode() and buildSteps() in
the page; tests/test_parity.py checks both against the page with node.

Nothing in this module imports orca or serial, so it runs (and is tested) outside OrcaSlicer. The
plugin glue opens the serial port and hands it to ColdPullSession.start_run(); any object with
read(n), write(bytes), close(), an `in_waiting` attribute and a read timeout of about SLICE_S works.
"""
import codecs
import os
import re
import sys
import threading
import time
import zipfile

FLUSH_MIN, FLUSH_MAX, FLUSH_DEFAULT = 200, 290, 290
PULL_MIN, PULL_MAX, PULL_DEFAULT = 60, 120, 80
BAUD = 115200
PRUSA_VID = 0x2C99
SLICE_S = 0.25  # read slice: how often a silent wait re-checks its deadline and force stop

PARK_NOTE = " The tool is still on the carriage. Park it from the printer's Control menu."


def _int_or(value, default):
    """parseInt(value) || default, as settings() in the page does it."""
    try:
        number = int(float(value))
    except (TypeError, ValueError, OverflowError):
        return default
    return number or default


def clamp_settings(nozzle, flush, pull, tool_count=8):
    """Mirror settings() in the page, with the nozzle range taken from the printer's tool count."""
    nozzle = min(tool_count, max(1, _int_or(nozzle, 1)))
    flush = min(FLUSH_MAX, max(FLUSH_MIN, _int_or(flush, FLUSH_DEFAULT)))
    pull = min(PULL_MAX, max(PULL_MIN, _int_or(pull, PULL_DEFAULT)))
    return {"tool": nozzle - 1, "nozzle": nozzle, "flush": flush, "pull": pull}


