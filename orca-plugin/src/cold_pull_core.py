def build_steps(tool, flush, pull, orig_filament):
    """Port of buildSteps() in the page: [(caption, command, timeout_s)].

    `orig_filament` is the tool's filament type as read back from the printer before the run; the
    restore step puts exactly that value back. None omits the restore (a name M865 cannot quote).
    """
    T = f"T{tool} M0"
    QUICK, MOVE, PICK, HEAT, COOL, PROMPT = 10, 60, 240, 900, 2400, 7200
    s = []
    s.append(("Confirm the setup prompt on the printer",
              "M0 Setup check: filament sensor OFF, PTFE tube removed. Press to continue", PROMPT))
    # Arm with an instant G-command: a long-blocking M109 as the first G-code would trip the
    # firmware's 5 s serial-print inactivity timeout (Prusa-Firmware-Buddy#5399).
    s.append(("Starting session", "G4 P1", QUICK))
    s.append(("Picking nozzle from its dock", T, PICK))
    # Firmware 6.9.0 removed the Auto Retract switch on INDX; marking the tool FLEX is the only
    # remaining way to stop the firmware retracting the plug back out of the melt zone.
    s.append(("Marking the tool FLEX to suppress auto retract", f'M865 S"FLEX" L{tool}', QUICK))
    s.append(("Allowing cold extrusion", "M302 S0", QUICK))
    s.append(("Switching to relative extrusion", "M83", QUICK))
    s.append(("Disabling stuck-filament detection", "M591 S0", QUICK))
    s.append(("Insert filament at the printer, then press the knob",
              "M0 Insert light PLA into the top port until it stops at the drive gears. Do not force it", PROMPT))
    s.append(("Heating nozzle to flush temperature", f"M109 S{flush}", HEAT))
    # Briefing before the purge: the screen and the nozzle cannot be watched at once.
    s.append(("Read the purge prompt, then watch the nozzle tip",
              "M0 Purge next. Watch the nozzle tip for melted PLA flowing out. Press to start", PROMPT))
    s.append(("Confirming nozzle is still at temperature", f"M109 S{flush}", HEAT))
    s.append(("Confirming nozzle is picked", T, PICK))
    for i in range(3):
        s.append((f"Pushing filament through ({i + 1} of 3)", "G1 E20 F120", MOVE))
        if i < 2:
            s.append(("Letting pressure settle", "G4 S2", MOVE))
    s.append(("Check the tip, then answer the prompt on the printer",
              "M0 Tip check. PLA out: press knob to continue. NOTHING out: press knob then cancel here", PROMPT))
    s.append(("Confirming nozzle is still at temperature", f"M109 S{flush}", HEAT))
    s.append(("Cooling toward 180 C while packing", "M104 S180", QUICK))
    s.append(("Confirming nozzle is picked", T, PICK))
    for i in range(8):
        s.append((f"Packing the melt zone ({i + 1} of 8)", "G1 E2 F60", MOVE))
        if i < 7:
            s.append(("Cooling 5 seconds", "G4 S5", MOVE))
    s.append(("Turning the heater off", "M104 S0", QUICK))
    s.append(("Fan to full", "M106 S255", QUICK))
    s.append(("Cooling to 60 C", "M109 R60", COOL))
    s.append(("Turning the heater off", "M104 S0", QUICK))
    s.append(("Holding 2 minutes to finish cooling", "G4 S120", 180))
    s.append(("Fan off", "M107", QUICK))
    # Two-stage warm-up so the PID does not overshoot the low pull temperature.
    s.append(("Warming toward pull temperature", f"M104 S{pull - 3}", QUICK))
    s.append(("Approaching from just below", f"M109 C{pull - 4}", HEAT))
    s.append(("Settling at pull temperature", f"M109 S{pull}", HEAT))
    s.append(("Keep hands clear, then press the knob to pull",
              f"M0 Pull ready at {pull}C. Motor will yank the plug - keep hands clear. Press to pull", PROMPT))
    s.append(("Restoring pull temperature", f"M104 S{pull - 3}", QUICK))
    s.append(("Approaching from just below", f"M109 C{pull - 4}", HEAT))
    s.append(("Confirming pull temperature", f"M109 S{pull}", HEAT))
    s.append(("Confirming nozzle is picked", T, PICK))
    s.append(("Raising extruder motor current", "M906 E650", QUICK))
    s.append(("Pulling the plug out", "G1 E-40 F3000", MOVE))
    s.append(("Feeding the strand up and out", "G1 E-40 F1200", MOVE))
    s.append(("Restoring motor current", "M906 E550", QUICK))
    s.append(("Restoring stuck-filament detection", "M591 R", QUICK))
    s.append(("Restoring cold-extrusion guard", "M302 S170", QUICK))
    s.append(("Turning the heater off", "M104 S0", QUICK))
    s.append(("Remove the strand at the printer, then press the knob",
              "M0 Done. Remove the strand and inspect the tip. Press to warm the nozzle and dock the tool", PROMPT))
    # Warm dock: P0 S1 docks the picked tool; warming first lets residue release in the dock.
    s.append(("Confirming nozzle is picked", T, PICK))
    s.append(("Warming the nozzle so residue releases in the dock", "M109 S170", HEAT))
    s.append(("Turning the heater off", "M104 S0", QUICK))
    s.append(("Docking the tool", "P0 S1", PICK))
    s.append(("Releasing the motors", "M84", QUICK))
    # Last, deliberately: FLEX must stay in force through the warm-up and the dock, or the firmware
    # would auto-retract the moment the tool reads as PLA again.
    if orig_filament is not None:
        s.append(("Restoring the tool's filament type", f'M865 S"{orig_filament}" L{tool}', QUICK))
    return s


def cleanup_commands(tool, orig_filament, flex_applied):
    """The commands cleanup() sends. The M865 restore only when the FLEX write was dispatched."""
    return ["M104 S0", "M107", "M302 S170", "M591 R", "M906 E550",
            *([f'M865 S"{orig_filament}" L{tool}'] if flex_applied else []), "M84"]


class ShutdownRequested(Exception):
    """OrcaSlicer is unloading the plugin; stop waiting and leave the printer as safe as possible."""


class _Flags:
    def __init__(self):
        self.abort = False
        self.force_stop = False
        self.shutdown = False


class Link:
    """Line protocol over a serial port: write a command, collect lines until a bare "ok"."""

    def __init__(self, port, flags, timeout_scale=1.0):
        self.port = port
        self.flags = flags
        self.timeout_scale = timeout_scale
        self.buf = ""
        self.dec = codecs.getincrementaldecoder("utf-8")("replace")
        self._write_lock = threading.Lock()

    def write(self, cmd):
        with self._write_lock:
            self.port.write((cmd + "\n").encode("utf-8"))

    def until_ok(self, timeout_s, collect=False, honor_force_stop=False):
        """Read until a bare "ok". Returns collected lines. Raises on timeout, force stop, shutdown.

        Reads in short slices so a printer that goes silent (unplugged, crashed) cannot hang the
        wait: the deadline and force stop are re-checked at least every SLICE_S.
        """
        lines = []
        deadline = time.monotonic() + timeout_s * self.timeout_scale
        while True:
            if self.flags.shutdown:
                raise ShutdownRequested()
            if self.flags.force_stop and honor_force_stop:
                raise RuntimeError("force-stop")
            if time.monotonic() > deadline:
                raise RuntimeError("timed out waiting for the printer")
            try:
                chunk = self.port.read(self.port.in_waiting or 1)
            except OSError as error:  # pyserial's SerialException is an OSError
                raise RuntimeError("serial port closed") from error
            if not chunk:
                continue
            self.buf += self.dec.decode(chunk)
            while "\n" in self.buf:
                line, self.buf = self.buf.split("\n", 1)
                line = line.strip()
                if line == "ok":
                    return lines
                if line and collect:
                    lines.append(line)

    def until_line(self, timeout_s, done):
        """Read lines until done(line) returns something other than None, and return it. For replies
        that do not end in a bare "ok" (M105 prints its own "ok T:..." and none at all on error)."""
        deadline = time.monotonic() + timeout_s * self.timeout_scale
        while True:
            if self.flags.shutdown:
                raise ShutdownRequested()
            if time.monotonic() > deadline:
                raise RuntimeError("timed out waiting for the printer")
            try:
                chunk = self.port.read(self.port.in_waiting or 1)
            except OSError as error:
                raise RuntimeError("serial port closed") from error
            if not chunk:
                continue
            self.buf += self.dec.decode(chunk)
            while "\n" in self.buf:
                line, self.buf = self.buf.split("\n", 1)
                result = done(line.strip())
                if result is not None:
                    return result

    def close(self):
        try:
            self.port.close()
        except Exception:
            pass


class ColdPullSession:
    """The log, the put-it-back reminder and at most one serial run.

    The run happens on a worker thread so a 30-minute procedure never blocks OrcaSlicer's UI thread.
    The worker never calls OrcaSlicer UI APIs: it appends to the log, and the page polls snapshot()
    through the plugin's on_message handler, which runs on the UI thread.
    """

    def __init__(self, on_finish=None, timeout_scale=1.0, log_limit=2000):
        self._lock = threading.Lock()
        self._log = []
        self._epoch = 0
        self._log_limit = log_limit
        self._restore = None
        self._run_settings = None
        self._thread = None
        self._flags = _Flags()
        self._on_finish = on_finish
        self.timeout_scale = timeout_scale
        self.last_outcome = None
        self.last_reason = None  # why a "rejected" run did not start
        self._ending = False     # the procedure is over; the thread is only wrapping up
        self.run_id = 0          # increments per run that reaches the printer; the page acks by it

    # ---- log and state, shared with the UI thread ----

    def say(self, text, cls=None):
        with self._lock:
            self._log.append({"text": text, "cls": cls or ""})
            if len(self._log) > self._log_limit:
                del self._log[: len(self._log) - self._log_limit]
                self._epoch += 1  # indices shifted; make the page re-render

    def clear_log(self):
        with self._lock:
            self._log = []
            self._epoch += 1

    def set_restore(self, after_run, fil_name, fil_changed, tool, auto_restored=True):
        """Data for showRestore() in the page. `tool` is 0-based, or None for every nozzle."""
        with self._lock:
            self._restore = {"after_run": after_run, "fil_name": fil_name, "fil_changed": fil_changed,
                             "tool": tool, "auto_restored": auto_restored}

    @property
    def running(self):
        thread = self._thread
        return thread is not None and thread.is_alive()

    @property
    def procedure_active(self):
        """True while the procedure itself is still executing. Unlike `running`, it turns false at
        the first step of wrapping up, before the port is closed and on_finish reports the result."""
        with self._lock:
            return self.running and not self._ending

    def snapshot(self, epoch=-1, count=0):
        """Log lines the page has not seen, plus the run state and the reminder."""
        with self._lock:
            full = epoch != self._epoch or count > len(self._log)
            start = 0 if full else count
            return {"epoch": self._epoch, "full": full, "start": start, "lines": self._log[start:],
                    "count": len(self._log), "running": self.running, "run_settings": self._run_settings,
                    "restore": self._restore, "outcome": self.last_outcome, "run_id": self.run_id}

    # ---- run control ----

    def begin_attempt(self, settings):
        """Called on the UI thread when Run is pressed, before the port is opened."""
        if self.running:
            raise RuntimeError("A cold pull is already running.")
        self.clear_log()
        self._flags = _Flags()
        with self._lock:
            self._run_settings = dict(settings)
            self.last_outcome = None
            self.last_reason = None
            self._ending = False

    def fail_attempt(self, settings, message):
        """The port never opened. The settings the user changed at the printer are still owed back,
        but the nozzle was never touched, so the filament-type row stays hidden."""
        self.say(f"Error: {message}", "err")
        with self._lock:
            self.last_outcome = "failed"
        self.set_restore(True, "PLA", False, settings["tool"], True)

    def start_run(self, port, settings):
        with self._lock:
            self.run_id += 1
        link = Link(port, self._flags, self.timeout_scale)
        self._thread = threading.Thread(target=self._run, args=(link, dict(settings)),
                                        name="indx-cold-pull", daemon=True)
        self._thread.start()

    def request_cancel(self):
        if not self.running:
            return
        self._flags.abort = True
        self.say("Cancel requested: stopping at the next step and restoring state.", "err")

    def request_force_stop(self):
        if not self.running:
            return
        self._flags.abort = True
        self._flags.force_stop = True
        self.say("FORCE STOP requested: sending M112.", "err")

    def shutdown(self, timeout=3.0):
        """Plugin unload or app exit: stop waiting, queue the cleanup commands, release the port."""
        self._flags.shutdown = True
        thread = self._thread
        if thread is not None and thread.is_alive():
            thread.join(timeout)

    def join(self, timeout=None):
        thread = self._thread
        if thread is not None:
            thread.join(timeout)

    # ---- the procedure (worker thread) ----

    def _cleanup(self, link, tool, orig_filament, flex_applied):
        self.say("Restoring printer state…", "stage")
        all_confirmed = True
        for cmd in cleanup_commands(tool, orig_filament, flex_applied):
            # Force stop must work from here: cleanup can block behind an M0 prompt, which is
            # exactly when someone reaches for the emergency stop.
            if self._flags.force_stop:
                self._send_m112(link)
                return False
            try:
                link.write(cmd)
                link.until_ok(5, honor_force_stop=True)
            except ShutdownRequested:
                raise
            except Exception:
                if self._flags.force_stop:
                    self._send_m112(link)
                    return False
                all_confirmed = False
        return all_confirmed

    def _dock_refusal(self, link, tool, nozzle):
        """None when nozzle `tool` is a dock the printer has enabled, else why the run must not start."""
        self.say(f"Checking that nozzle {nozzle}'s dock is enabled…", "stage")
        link.write("M863")
        mapping = link.until_ok(10, collect=True)
        enabled = re.search(r"Enabled:\s*(\S+)", "\n".join(mapping))
        if enabled and enabled.group(1).lower() not in ("0", "false"):
            return ("tool mapping is active on the printer, so the plugin cannot check which dock nozzle "
                    f"{nozzle} is. Finish or stop the print that set it, or restart the printer.")
        link.write(f"M105 T{tool}")

        def answer(line):
            if "Invalid extruder" in line:
                return "disabled"
            if line == "ok" or line.startswith("ok "):
                return "enabled"
            return None

        try:
            state = link.until_line(10, answer)
        except RuntimeError as error:
            if "timed out" not in str(error):
                raise
            return f"the printer did not say whether nozzle {nozzle}'s dock is enabled."
        if state == "disabled":
            return f"nozzle {nozzle}'s dock is not enabled on this printer."
        return None

    def _send_m112(self, link):
        try:
            link.write("M112")
            self.say("M112 sent.", "err")
        except Exception:
            pass

    def _queue_cleanup_unconfirmed(self, link, tool, orig_filament, flex_applied):
        """On shutdown there is no time to wait for each ok. The commands queue behind whatever the
        printer is doing (an M0 prompt included) and run once it gets there."""
        for cmd in cleanup_commands(tool, orig_filament, flex_applied):
            try:
                link.write(cmd)
            except Exception:
                break
        print("INDX Cold Pull: OrcaSlicer unloaded the plugin mid-run; cleanup commands were queued "
              "without confirmation.", file=sys.stderr)

    def _run(self, link, s):
        tool, nozzle = s["tool"], s["nozzle"]
        outcome = "completed"
        reason = None
        confirmed_indx = False
        tool_picked = False
        orig_filament = "PLA"
        flex_applied = False
        filament_restorable = True
        orig_filament_raw = ""

        def park_note():
            return PARK_NOTE if tool_picked else ""

        try:
            # Model gate: toolchanger picks, high temperatures and INDX motor currents are wrong
            # and potentially damaging on an MK4/XL/MINI. Refuse anything that is not an INDX.
            self.say("Identifying printer…", "stage")
            link.write("M115")
            info = link.until_ok(10, collect=True)
            match = re.search(r"MACHINE_TYPE:(\S+)", " ".join(info))
            model = match.group(1) if match else ""
            if not re.search("INDX", model, re.IGNORECASE):
                reason = f'this port reports "{model or "an unknown model"}", not an INDX.'
                self.say(f"Refusing to continue: {reason}", "err")
                self.say("Nothing was sent. Pick the INDX's port, or use the G-code file.", "err")
                outcome = "rejected"
                return
            confirmed_indx = True
            self.say(f"Confirmed {model}.", "good")

            # Dock gate. Picking a tool whose dock is not enabled is a fatal toolchanger error on
            # INDX (toolchanger_indx.cpp: "Toolchange to tool that is not enabled"), and the count
            # M115 reports says nothing about which docks those are. M105 T<n> asks about one dock
            # without side effects: GcodeSuite::get_target_physical_from_optional() answers
            # "Invalid extruder <n>" and stops for a disabled tool, else M105 prints "ok T:...".
            # Its T goes through tool mapping while the pick (T<n> M0) does not, so only probe
            # when M863 reports mapping off (it is reset when a print ends).
            reason = self._dock_refusal(link, tool, nozzle)
            if reason is not None:
                self.say(f"Refusing to continue: {reason}", "err")
                self.say("Only read-only queries were sent. Picking a tool whose dock is not enabled crashes the "
                         "printer, so the procedure does not start without that check.", "err")
                outcome = "rejected"
                return

            # M865 I<n> echoes the tool's filament as "name:<TYPE>". Only a missing name may end
            # in a value this plugin chose; an unsendable name is left alone, never overwritten.
            self.say("Reading the tool's filament type…", "stage")
            link.write(f"M865 I{tool}")
            fil_info = link.until_ok(10, collect=True)
            name_line = re.search(r"^name:(.*)$", "\n".join(fil_info), re.MULTILINE)
            orig_filament_raw = name_line.group(1).strip() if name_line else ""
            if not orig_filament_raw:
                self.say(f"Nozzle {nozzle} has no filament type set. It will be left as PLA afterwards; "
                         "clear it from the printer's Filament menu if you want it empty.", "err")
            elif re.fullmatch(r"[A-Za-z0-9_-]+", orig_filament_raw):
                orig_filament = orig_filament_raw
                self.say(f"Nozzle {nozzle} is set to {orig_filament}; it will be put back after the pull.")
            else:
                filament_restorable = False
                self.say(f'Nozzle {nozzle} is set to "{orig_filament_raw}", a name this plugin cannot send back '
                         "over G-code. Nothing will be written back: the nozzle will be left marked FLEX, and "
                         f'you must set it to "{orig_filament_raw}" yourself from the printer\'s Filament menu.', "err")

            steps = build_steps(tool, s["flush"], s["pull"], orig_filament if filament_restorable else None)
            for caption, cmd, timeout in steps:
                if self._flags.abort:
                    outcome = "force-stopped" if self._flags.force_stop else "canceled"
                    if self._flags.force_stop:
                        link.write("M112")
                        self.say("M112 sent. Reset the printer before continuing.", "err")
                        break
                    ok = self._cleanup(link, tool, orig_filament, flex_applied and filament_restorable)
                    if ok:
                        self.say("Canceled. Printer state restored." + park_note(), "good")
                    else:
                        self.say("Canceled, but the printer did not confirm cleanup. CHECK IT DIRECTLY. "
                                 "The nozzle may still be hot." + park_note(), "err")
                    break
                self.say(caption, "stage")
                try:
                    # The write belongs inside the guard: a USB disconnect mid-procedure raises here
                    # and must still reach the cleanup below.
                    link.write(cmd)
                    # A pick can complete even when its ok is lost; only a confirmed dock clears it.
                    if cmd.startswith("T"):
                        tool_picked = True
                    # Same for FLEX: treating a landed write as un-applied would skip the restore.
                    if cmd.startswith('M865 S"FLEX"'):
                        flex_applied = True
                    link.until_ok(timeout, honor_force_stop=True)
                    if cmd == "P0 S1":
                        tool_picked = False
                except ShutdownRequested:
                    raise
                except Exception as error:
                    outcome = "force-stopped" if self._flags.force_stop else "failed"
                    if self._flags.force_stop:
                        try:
                            link.write("M112")
                            self.say("M112 sent. Reset the printer before continuing.", "err")
                        except Exception:
                            self.say("Force stop could NOT be sent: the connection is gone. CHECK THE PRINTER "
                                     "DIRECTLY, it may still be hot.", "err")
                        break
                    self.say(f"Failed: {error}", "err")
                    ok = self._cleanup(link, tool, orig_filament, flex_applied and filament_restorable)
                    if ok:
                        self.say("Printer state restored." + park_note(), "good")
                    else:
                        self.say("The printer did not confirm cleanup. CHECK IT DIRECTLY. The nozzle may still be "
                                 "hot, and the extrusion guard may still be disabled." + park_note(), "err")
                    break
            if outcome == "completed":
                self.say("Cold pull complete. Inspect the tip: three thin strands with debris is a good pull.", "good")
        except ShutdownRequested:
            outcome = "interrupted"
            if confirmed_indx:
                self._queue_cleanup_unconfirmed(link, tool, orig_filament, flex_applied and filament_restorable)
        except Exception as error:
            outcome = "failed"
            self.say(f"Error: {error}", "err")
            # Only clean up once the printer is positively an INDX: cleanup sends M906 E550, an
            # INDX motor current, and before the gate passes only M115 has been sent.
            if confirmed_indx:
                try:
                    ok = self._cleanup(link, tool, orig_filament, flex_applied and filament_restorable)
                except ShutdownRequested:
                    self._queue_cleanup_unconfirmed(link, tool, orig_filament, flex_applied and filament_restorable)
                    ok = False
                if ok:
                    self.say("Printer state restored." + park_note(), "good")
                else:
                    self.say("The printer did not confirm cleanup. CHECK IT DIRECTLY. The nozzle may still be hot."
                             + park_note(), "err")
        finally:
            with self._lock:
                self._ending = True  # first, so nothing reads this run as still in progress
            link.close()
            with self._lock:
                self.last_outcome = outcome
                self.last_reason = reason
            # Owed on every exit; the filament row only when the FLEX write was dispatched.
            self.set_restore(True, orig_filament if filament_restorable else orig_filament_raw,
                             flex_applied, tool, filament_restorable)
            if self._on_finish is not None:
                try:
                    self._on_finish(outcome, self._restore, reason)
                except Exception as error:
                    print(f"INDX Cold Pull: on_finish failed: {error}", file=sys.stderr)


# ---- G-code files ----

def gcode_filename(nozzle):
    return f"cold_pull_nozzle{nozzle}.gcode"


ALL_ZIP_NAME = "cold_pull_all_nozzles.zip"


def list_destinations():
    """Folders the G-code can be saved to: mounted removable drives first, then Downloads."""
    dests = []
    if sys.platform == "darwin":
        bases = ["/Volumes"]
    elif sys.platform.startswith("linux"):
        user = os.environ.get("USER", "")
        bases = [p for p in (f"/media/{user}", f"/run/media/{user}") if user]
    else:
        bases = []
    for base in bases:
        try:
            names = sorted(os.listdir(base))
        except OSError:
            continue
        for name in names:
            path = os.path.join(base, name)
            # On macOS the boot volume appears in /Volumes as a symlink to "/".
            if os.path.realpath(path) == "/" or not os.path.ismount(path):
                continue
            dests.append({"id": path, "label": name, "kind": "drive"})
    if os.name == "nt" and hasattr(os, "listdrives"):
        system_drive = os.environ.get("SystemDrive", "C:").upper()
        try:
            drives = os.listdrives()
        except OSError:
            drives = []
        for drive in drives:
            if not drive.upper().startswith(system_drive):
                dests.append({"id": drive, "label": drive.rstrip("\\"), "kind": "drive"})
    downloads = os.path.join(os.path.expanduser("~"), "Downloads")
    if os.path.isdir(downloads):
        dests.append({"id": downloads, "label": "Downloads folder", "kind": "folder"})
    return dests


def write_gcode(folder, settings):
    """Write one nozzle's file. Returns its path."""
    path = os.path.join(folder, gcode_filename(settings["nozzle"]))
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(generate_gcode(settings["tool"], settings["flush"], settings["pull"]))
    return path


def write_all_zip(folder, settings, tool_count):
    """One archive with a file per nozzle, as the page's "all nozzles" download builds it."""
    path = os.path.join(folder, ALL_ZIP_NAME)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_STORED) as archive:
        for tool in range(tool_count):
            archive.writestr(gcode_filename(tool + 1), generate_gcode(tool, settings["flush"], settings["pull"]))
    return path
